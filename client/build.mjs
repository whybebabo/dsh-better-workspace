/**
 * Bundles the browser half into `lib/client.js`.
 *
 * Output is CommonJS wrapped in the `window.__ModuleLoader__.load({ id, factory })` shell the
 * DSH client uses for plugin bundles: `require` inside the factory is the loader's own
 * resolver, so `react` and the `@deepseek-ai/*` baseline modules stay external and resolve to
 * the host's already-loaded copies instead of a second React instance.
 */
import { build } from 'esbuild';
import { mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const outDir = join(root, 'lib');
const bundlePath = join(outDir, '.client.bundle.cjs');
const finalPath = join(outDir, 'client.js');

/**
 * The registration id the client-modules loader requires: it names a bundle by the
 * package.json `name` of the row that owns it, so the bundle MUST register exactly that
 * string. Reading it here instead of hardcoding keeps the short historical id
 * (`dsh-better-workspace`) from surviving a rename to the scoped npm name — the mismatch
 * makes the loader report "loaded without registering" and the whole entry fails to boot.
 * Note the loader normalizes a trailing `/client`, so the bare package name is the id.
 */
const MODULE_ID = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).name;
if (typeof MODULE_ID !== 'string' || MODULE_ID.length === 0) {
  throw new Error('package.json 缺少 name:无法确定 client 模块注册 id');
}

const external = [
  'react',
  'react-dom',
  'react/jsx-runtime',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-layout',
  '@deepseek-ai/dsh-client-ui-sidebar',
  '@deepseek-ai/dsh-client-ui-workspace',
  '@deepseek-ai/dsh-client-ui-conversation',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-locale',
  '@deepseek-ai/dsh-client-connection',
  '@deepseek-ai/cordis',
];

await build({
  absWorkingDir: root,
  entryPoints: ['client/index.jsx'],
  outfile: bundlePath,
  bundle: true,
  platform: 'browser',
  format: 'cjs',
  target: ['es2020'],
  jsx: 'transform',
  jsxFactory: 'React.createElement',
  jsxFragment: 'React.Fragment',
  loader: { '.css': 'text' },
  // The browser half stamps its <style> with the same id the loader keys plugins by, so HMR
  // can inventory and remove exactly this plugin's styles.
  define: { __DSH_CLIENT_ID__: JSON.stringify(MODULE_ID) },
  external,
  charset: 'utf8',
  legalComments: 'none',
  logLevel: 'info',
  logLimit: 0,
});

const code = readFileSync(bundlePath, 'utf8');
if (/\bimport\s|\bexport\s/.test(code)) {
  throw new Error('esbuild 输出包含 ESM 语法,无法包进 CJS 工厂:请检查 format/external');
}

const indented = code
  .split('\n')
  .map((line) => (line.length > 0 ? `\t\t${line}` : line))
  .join('\n');

const shell = `// ${MODULE_ID} client bundle — generated by client/build.mjs, do not edit.
// The plugin's browser half registers into the shell's \`shell.overlay\` slot and covers the
// native workspace region; the node half (lib/index.js) owns the topic sidecar and routes.
window.__ModuleLoader__.load({
\tid: ${JSON.stringify(MODULE_ID)},
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: 'Module' });
${indented}
\t\treturn module.exports;
\t},
});
`;

if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });
writeFileSync(finalPath, shell, 'utf8');
rmSync(bundlePath, { force: true });

const bytes = Buffer.byteLength(shell, 'utf8');
console.log(`lib/client.js written: ${(bytes / 1024).toFixed(1)} KB (external: ${external.length} modules)`);
